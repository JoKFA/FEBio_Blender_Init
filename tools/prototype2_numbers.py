def commit_text(prov: dict) -> str:
    src = prov["software"]["asrp_source"]
    return src["commit"][:7] + ("（有未提交的改动）" if src["dirty"] else "")


def load(files: dict[str, Path] = FILES) -> dict[str, str]:
    return build(load_all(files))


# ---------------------------------------------------------------- the markers (the same mechanism as prototype_numbers)

def find_blocks(text: str) -> tuple[dict[str, tuple[int, int]], list[str]]:
    spans: dict[str, tuple[int, int]] = {}
    problems: list[str] = []
    open_name, open_at = None, 0
    for m in MARKER.finditer(text):
        name = m.group(1)
        if m.group(0).startswith("<!-- BEGIN"):
            if open_name is not None:
                problems.append(f"{name}: BEGIN inside the unfinished block {open_name}")
            if name in spans:
                problems.append(f"{name}: appears twice")
            open_name, open_at = name, m.end()
        else:
            if open_name != name:
                problems.append(f"{name}: END without its BEGIN")
            else:
                spans[name] = (open_at, m.start())
            open_name = None
        line_start = text.rfind("\n", 0, m.start()) + 1
        line_end = text.find("\n", m.end())
        if text[line_start:line_end if line_end != -1 else len(text)].strip() != m.group(0):
            problems.append(f"{name}: the marker must be alone on its line")
    if open_name is not None:
        problems.append(f"{open_name}: BEGIN without its END")
    return spans, problems


def apply(text: str, blocks: dict[str, str]) -> tuple[str, list[str]]:
    spans, problems = find_blocks(text)
    problems += [f"{n}: no marker pair in the page" for n in blocks if n not in spans]
    problems += [f"{n}: marker pair has no generator" for n in spans if n not in blocks]
    if problems:
        return text, problems
    for name, (start, end) in sorted(spans.items(), key=lambda kv: -kv[1][0]):
        text = text[:start] + "\n" + blocks[name] + "\n" + text[end:]
    return text, []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite the generated blocks in the page")
    mode.add_argument("--check", action="store_true", help="exit 1 if the page differs from what --write would write")
    ap.add_argument("--doc", type=Path, default=DOC, help="the page to check or rewrite (default docs/15-prototype.md)")
    args = ap.parse_args(argv)
    blocks = load()
    if not (args.write or args.check):
        for name, md in blocks.items():
            print(f"--- {name}\n{md}\n")
        return 0
    old = base.read_text(args.doc)
    new, problems = apply(old, blocks)
    if problems:
        print("prototype two page markers are wrong:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    if args.check:
        spans_old, _ = find_blocks(old)
        spans_new, _ = find_blocks(new)
        stale = [n for n in blocks if old[slice(*spans_old[n])] != new[slice(*spans_new[n])]]
        if stale:
            print("docs/15 section 8 is out of date with the archived runs; run tools/prototype2_numbers.py with --write. "
                  "Differs in block(s): " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"ok: {len(blocks)} generated blocks match the archive")
        return 0
    if new != old:
        with open(args.doc, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
    print(f"wrote {len(blocks)} blocks into {args.doc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

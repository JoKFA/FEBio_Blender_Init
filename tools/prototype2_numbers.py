    # --- c. A and B side by side
    dist, norm_all = st["distance_to_target"], st["normalised_distance_all_vertices"]
    blocks["p2-distance"] = base.table(
        ["最后一帧的形状", "离目标：最大 (mm)", "离目标：平均 (mm)", "归一化距离（我们的变体：全部顶点）"],
        [[VARIANT[k], mm2(dist[k]["max_mm"]), mm2(dist[k]["mean_mm"]), f"{norm_all[k]:.3f}"]
         for k in ("physics_only", "a", "b")])

    if st["normalised_distance"] is None:
        blocks["p2-normalised"] = (
            "**实验室目标函数里的那个归一化距离，这里没有按实验室的定义算出来**（报告里它的值是空，写明了原因）。"
            "实验室的那一项是在它采样的控制顶点上，到目标的欧氏距离除以起点的欧氏距离；采样的顶点集是实验室几个采样列表拼起来的，"
            "起点是它收到的 `s_next`，这两样我们现在都确定不了，所以不报一个看起来像它的数。上表最后一列是**我们自己的变体**："
            f"`{st['normalised_distance_all_vertices']['definition']}`。它**不是实验室的数**，不能当作实验室会得到的值来读。")

"""Write the numbers of docs/15-prototype.md from the archived reference run, so they cannot drift.

    uv run python tools/prototype_numbers.py            # print every generated block
    uv run python tools/prototype_numbers.py --write    # rewrite the blocks inside docs/15
    uv run python tools/prototype_numbers.py --check    # exit 1, naming the block, if docs/15 differs

The numbers come from the two archived files data/preview/prototype_run_report.json and
data/preview/prototype_provenance.json. The explanatory Chinese text in each table row is fixed
text in this file; every number, every verdict (passed, failed, not run), the retry count, the settled
frame and every scene fact the tables state comes from the JSON, and a claim the JSON does not hold is
not written. In docs/15 each table sits
between a pair of marker comments

    <!-- BEGIN generated by tools/prototype_numbers.py: NAME -->
    ...
    <!-- END generated: NAME -->

and text outside the markers is never touched. After archiving a new reference run, copy the two
JSON files into data/preview and run this tool with --write. tests/test_prototype_page.py runs
--check, so tools/verify.py fails when the page and the archive disagree.
"""

import argparse
import json
import math
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOC = REPO / "docs" / "15-prototype.md"
REPORT = REPO / "data" / "preview" / "prototype_run_report.json"
PROVENANCE = REPO / "data" / "preview" / "prototype_provenance.json"

BEGIN = "<!-- BEGIN generated by tools/prototype_numbers.py: {name} -->"
END = "<!-- END generated: {name} -->"
MARKER = re.compile(r"<!-- (?:BEGIN generated by tools/prototype_numbers\.py|END generated): ([\w-]+) -->")

NOT_MEASURED = (
    "存档的这一次只跑了一遍，报告里没有重复运行的数据；两次运行相差多少见第 3 节（ADR-38）"
)
GROUP_NAME = {
    "upper_lip_on_skull": "上唇",
    "lower_lip_on_jaw": "下唇",
    "left_corner_on_anchor": "左嘴角",
    "right_corner_on_anchor": "右嘴角",
}
BODY_TEXT = {"skull": "颅骨", "jaw": "下颌", "lip_corner_anchor": "嘴角锚"}
SUPERSCRIPT = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")


def sci(x: float) -> str:
    """9.63×10⁻¹¹ for tiny values; three significant digits otherwise (0.0334, 0.00115)."""
    if x == 0:
        return "0"
    if abs(x) >= 1e-3:
        return f"{x:.3g}"
    exp = math.floor(math.log10(abs(x)))
    mant = round(x / 10**exp, 2)
    if abs(mant) >= 10:
        mant, exp = mant / 10, exp + 1
    return f"{mant:.2f}×10{str(exp).translate(SUPERSCRIPT)}"


def sec(x: float) -> str:
    return f"{x:.2f} s"


def mm4(x: float) -> str:
    return f"{x:.4f} mm"


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def ratio3(x) -> str:
    """A volume ratio with three decimals; a ratio the report holds as null (not a finite number) says so."""
    return "无有限值" if x is None else f"{x:.3f}"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def param(report: dict, where: str):
    for p in report["parameters"]:
        if p["where"] == where:
            return p["value"]
    raise KeyError(where)


def param_row(report: dict, where_regex: str) -> dict | None:
    """The first parameter row whose `where` matches the regex, or None."""
    for p in report["parameters"]:
        if re.search(where_regex, p["where"]):
            return p
    return None


def threads(prov: dict) -> int:
    return int(prov["parameters"]["febio_env"]["OMP_NUM_THREADS"])


def verdict(check: dict) -> str:
    """The check's verdict as the page words it: only the JSON decides."""
    return {True: "通过", False: "**不通过**", None: "没运行"}[check["passed"]]


def cell(check: dict, detail) -> str:
    """The result cell of a check: passed -> verdict and the detail (a function, called only then); failed ->
    verdict and the check's own message; not run -> verdict and the reason."""
    if check["passed"] is True:
        text = detail()
        return f"{verdict(check)}：{text}" if text else verdict(check)
    return f"{verdict(check)}：{check['message']}"


def retry_phrase(retries: int) -> str:
    return ("FEBio 没有哪一步要缩小步长重算" if retries == 0
            else f"FEBio 有 {retries} 次缩小步长重算（算出来了，但记在这里）")


def group_label(g: dict) -> str:
    """'上唇 → 颅骨（`hard`）': the kind and the body come from the report's group, the short name from a table."""
    return f"{GROUP_NAME.get(g['name'], g['name'])} → {BODY_TEXT.get(g['to'], g['to'])}（`{g['kind']}`）"


def find_group(gen: dict, name: str) -> dict | None:
    return next((g for g in gen["groups"] if g["name"] == name), None)


def build(report: dict, prov: dict) -> dict[str, str]:
    """Block name -> Markdown, in the order they appear in the page. Every verdict, count and scene fact comes from
    the two archived files; nothing is assumed about the order of lists."""
    c = report["checks"]
    ca, cb, cb2, ccheck, cd = (c[k] for k in ("a", "b", "b2", "c", "d"))
    a, b, b2, cc, d = (x["numbers"] for x in (ca, cb, cb2, ccheck, cd))
    t, gen = report["timing"], report["generator"]
    n_threads = threads(prov)
    steps = a["frames_logged"]
    retries = a["retries"]
    fps = param(report, "scene.solver.fps")
    shape = report.get("settled_shape", {})
    settled = shape.get("frame") if shape.get("available") else None
    spring_dev = b["spring_display_deviation"]
    groups = {g["name"]: g for g in gen["groups"]}
    # The lip the jaw drives, by name; any other spring group stands in if the scene has none of that name.
    lip_name = "lower_lip_on_jaw" if "lower_lip_on_jaw" in spring_dev else (
        max(spring_dev, key=lambda n: spring_dev[n]["max_mm"]) if spring_dev else None)
    lip = spring_dev.get(lip_name)
    source_text = str(param_row(report, r"^trajectory\.source$")["value"]) if param_row(report, r"^trajectory\.source$") else ""
    opens = re.search(r"opens to ([\d.]+) degrees at frame (\d+)", source_text)
    motion = report.get("motion")
    blocks: dict[str, str] = {}

    run_text = (f"{a['frames']} 帧全部算完（第 0 帧加 FEBio 算的 {steps} 步），**重试 {retries} 次**"
                if ca["passed"] is True else cell(ca, lambda: ""))
    hard_dev = max(b["hard_nodes_max_deviation_mm"], b["hard_display_vertices_max_deviation_mm"])
    if cb["passed"] is True:
        bone_text = f"上唇和颅骨粘住的地方，偏离**不超过 {sci(hard_dev)} mm**"
        if lip:
            peak = "，张得最大" if opens and int(opens.group(2)) == lip["worst_frame"] else ""
            bone_text += (f"；用弹簧挂着的{GROUP_NAME.get(lip_name, lip_name)}，最远偏离 "
                          f"**{sci(lip['max_mm'])} mm**（第 {lip['worst_frame']} 帧{peak}）")
        bone_meaning = ("贴骨头的地方确实跟着骨头走（这一条按做法本来就该成立，它查的是管线有没有接对，不是物理证据）；"
                        "弹簧处允许有一点点\"滑\"，滑得很小")
    else:
        bone_text, bone_meaning = cell(cb, lambda: ""), "见第 4 节检查 (b)"
    if ccheck["passed"] is True:
        sag_text = (f"自由部分的嘴唇第 {cc['frames'][0]}–{cc['frames'][1]} 帧平均顺重力下沉 "
                    f"**{cc['mean_sag_along_gravity_mm']:.4f} mm**；按材料和尺寸估计是 {cc['expected_sag_mm']:.4f} mm")
        sag_meaning = "方向对，量级和估计同一个数量级；估计本身是粗的，不证明准（第 5 节）"
    else:
        sag_text, sag_meaning = cell(ccheck, lambda: ""), "见第 4 节检查 (c)"
    if cd["passed"] is True:
        mesh_text = (f"{d['tets']:,} 个四面体里，翻转的 **{d['inverted_tets']} 个**；"
                     f"体积是静止时的 {ratio3(d['min_volume_ratio'])}（第 {d['min_volume_ratio_frame']} 帧）"
                     f"到 {ratio3(d['max_volume_ratio'])} 倍")
        mesh_meaning = "没有四面体翻面，但个别很小的四面体胀得不少，见第 5 节"
    else:
        mesh_text, mesh_meaning = cell(cd, lambda: ""), "见第 4 节检查 (d)"

    glance = [
        ["整段运动算完了吗", run_text, retry_phrase(retries) if ca["passed"] is True else "见第 4 节检查 (a)"],
        ["算得多快",
         f"{n_threads} 线程：FEBio **{sec(t['febio_s'])}**，**{t['febio_s_per_frame']:.2f} 秒/帧**",
         "机器同时在做别的事就会慢。**这是嘴唇一块组织的速度，不能拿来和 Ziva 比**：实验室演示机上 Ziva 每帧约 1.5–2.5 秒"
         "（[14](14-ziva-demo-walkthrough.md) 第 2 节），算的是整张脸（41 块软组织，[03](03-asset.md) 第 2 节）。"
         "线程数和更早的单线程用时见第 3 节"],
        ["嘴唇有没有\"脱\"骨头", bone_text, bone_meaning],
        ["重力有没有往下拉", sag_text, sag_meaning],
        ["网格有没有被压坏", mesh_text, mesh_meaning],
    ]
    if motion:
        jaw = f"下颌张 {float(opens.group(1)):g}°，" if opens else ""
        big = motion["max_display_distance_mm"]
        glance.append(["嘴唇动了多少",
                       f"{jaw}嘴唇上动得最多的顶点离开静止位置 **{big:.1f} mm**（第 {motion['frame']} 帧）",
                       "肉眼可见的大幅度运动" if big >= 5 else "位移很小"])
    glance.append(["同样的输入，同样的输出吗", NOT_MEASURED, "这一份运行报告本身不证明可复现"])
    blocks["glance"] = table(["看什么", "数字", "意思"], glance)

    if settled is None:
        back = f"没有（{shape.get('reason', '这次运行没有写沉降形状')}），所以没有这个测量"
    else:
        rts = report.get("return_to_settled", {})
        if rts.get("frames"):
            back = (f"第 {', '.join(map(str, rts['frames']))} 帧：四面体节点离沉降形状最多 {mm4(rts['max_mm'])}，"
                    f"平均 {mm4(rts['mean_mm'])}（沉降形状在第 {settled} 帧，重力的沉降当时还差这么一点没走完，"
                    "[13](13-explanations.md) E-08）")
        else:
            back = f"沉降形状在第 {settled} 帧，但之后没有一帧所有驱动都回到静止，所以没有这个测量"
    blocks["run"] = table(["项", "结果"], [
        ["帧数",
         f"{a['frames']}（第 0 帧是静止姿态，FEBio 算 {steps} 步；运动文件 {fps} 帧/秒，约 {(a['frames'] - 1) / fps:.1f} 秒）"],
        ["FEBio 重试", f"{retries} 次" + ("（步长从没有被迫缩小）" if retries == 0 else "（步长被迫缩小过）")],
        ["用时（存档的这一次）",
         f"FEBio {sec(t['febio_s'])}（{t['febio_s_per_frame']:.2f} 秒/帧，{n_threads} 线程，"
         f"[05](05-ziva-to-febio.md) 坑 17），生成 {sec(t['generate_s'])}，后处理 {sec(t['post_s'])}。"
         "只算了嘴唇一块，所以只报告用时，不和全脸的预算比"],
        ["同输入两次", NOT_MEASURED],
        ["回到沉降形状（只报告，不判）", back],
    ])

    lo_hi = cc.get("range_mm")
    blocks["checks"] = table(["检查", "一句话", "结果", "上限"], [
        ["(a) 整段算完", f"{a['frames']} 帧都算出来了，FEBio 中途没有失败",
         cell(ca, lambda: f"重试 {retries} 次"), "没有失败的帧"],
        ["(b) 粘在骨头上的点跟着骨头", "上唇粘在颅骨上的计算点和显示顶点，每一帧相对骨头不动",
         cell(cb, lambda: f"计算点最多偏 {sci(b['hard_nodes_max_deviation_mm'])} mm，显示顶点 "
                          f"{sci(b['hard_display_vertices_max_deviation_mm'])} mm"), f"{b['tolerance_mm']} mm"],
        ["(b2) 弹簧锚点跟着刚体", "下唇、嘴角的弹簧另一头钉在下颌、嘴角锚上，钉的位置每一帧都对",
         cell(cb2, lambda: f"全部 {b2['anchor_nodes']:,} 个锚点最多偏 {sci(b2['max_deviation_mm'])} mm（"
                           + "，".join(f"{BODY_TEXT.get(n, n)} {v['anchor_nodes']:,} 个" for n, v in b2["per_body"].items())
                           + "）"), f"{b2['tolerance_mm']} mm"],
        ["(c) 重力下垂和模型的估计一致", "没有粘住的嘴唇顶点在第 "
         f"{cc['frames'][0]}–{cc['frames'][1]} 帧平均往下沉了多少，和按密度、重力、k、E、尺寸算出的估计比",
         cell(ccheck, lambda: f"沉 {mm4(cc['mean_sag_along_gravity_mm'])}，估计 {mm4(cc['expected_sag_mm'])}"
                              f"（自由部分最远 {cc['free_length_mm']:.2f} mm）"),
         (f"估计的 1/{cc['factor']:g} 到 {cc['factor']:g} 倍：{mm4(lo_hi[0])} 到 {mm4(lo_hi[1])}" if lo_hi else "—")],
        ["(d) 四面体网格保持有效", "每一帧每个四面体的体积除以静止体积，没有翻面（体积 ≤ 0）",
         cell(cd, lambda: f"{d['tets']:,} 个四面体、{d['frames']} 帧，翻转 {d['inverted_tets']} 个；"
                          f"体积比最小 {ratio3(d['min_volume_ratio'])}（第 {d['min_volume_ratio_frame']} 帧），"
                          f"最大 {ratio3(d['max_volume_ratio'])}"),
         "没有翻转的四面体"],
    ])

    blocks["spring-deviation"] = table(["弹簧组", "显示顶点偏离目标：最大", "平均", "最大值出现的帧"], [
        [group_label(groups[n]) if n in groups else n, f"{sci(v['max_mm'])} mm", f"{sci(v['mean_mm'])} mm",
         f"第 {v['worst_frame']} 帧"]
        for n, v in spring_dev.items()
    ])

    blocks["springs"] = table(["弹簧组", "max\\|u\\|/δ", "判断"], [
        [group_label(groups[n]).split("（")[0] if n in groups else n, sig3(v["ratio"]),
         "< 0.1，没问题" if not v["flag"] else "**超过 0.1，要加大 δ**"]
        for n, v in report["spring_slip"].items()
    ])

    k = gen["physics_length_scale_k"]
    rows = [
        ["物理尺度 k", f"{k}"],
        ["计算点、四面体",
         f"{gen['febio_nodes']['tissue']:,} 个计算点、{gen['tets']:,} 个四面体（边长中位数 {gen['median_tet_edge_mm']:.2f} mm）"],
        ["显示网格到四面体的最远距离",
         f"{gen['display_max_distance_mm']:.3f} mm（上限 {gen['max_distance_limit_mm']:.2f} mm，"
         f"即 {param(report, 'generator.max_distance_edges'):g} 倍边长中位数；超过会报错停止）"],
    ]
    for g in gen["groups"]:
        name = group_label(g)
        if g["kind"] == "hard":
            rows.append([name, f"{g['display_vertices']} 个顶点 → {g['nodes']} 个计算点，并入{BODY_TEXT.get(g['to'], g['to'])}；"
                               f"被截成 0 的重心坐标 {g['clipped_coordinates']} 个；冲突 {g['conflicts']}"])
        else:
            rows.append([name, f"{g['display_vertices']} 个顶点 → {g['nodes']} 个计算点，{g['springs']} 根弹簧，"
                               f"{g['level_count']} 档刚度（最大档内误差 {pct(g['max_level_error'])}）"])
    springy = sorted((g for g in gen["groups"] if g["kind"] == "spring" and "base_stiffness_n_per_mm" in g),
                     key=lambda g: g["name"])
    tol = param(report, "generator.spring_level_tolerance")
    if springy:
        bases = {g["base_stiffness_n_per_mm"] for g in springy}
        e_row = param_row(report, r"\.material\.E_mpa$")
        e_mpa = e_row["value"] if e_row else None
        rule = None
        note = (param_row(report, rf"^scene\.attachments\[{re.escape(springy[0]['name'])}\]\.stiffness$") or {}).get("note", "")
        m = re.search(r"([\d.]+) x E x h", note)
        if m and e_mpa and len(bases) == 1:
            h = next(iter(bases)) / (float(m.group(1)) * e_mpa)
            rule = f"{m.group(1)} × E × h，E = {e_mpa} MPa，h = {h:.2f} mm"
        base_text = " / ".join(f"{x:.2f}" for x in sorted(bases)) + " N/mm" + (f"（{rule}）" if rule else "")
        per_group = "；".join(
            f"{GROUP_NAME.get(g['name'], g['name'])} {g['node_stiffness_n_per_mm']['min']:.2f}–"
            f"{g['node_stiffness_n_per_mm']['max']:.2f} N/mm" for g in springy)
        same_total = all(abs(g["node_stiffness_n_per_mm"]["sum"] - g["base_stiffness_n_per_mm"] * g["weight_sum"])
                         <= 1e-6 * g["node_stiffness_n_per_mm"]["sum"] for g in springy)
        rows.append(["弹簧基础刚度",
                     f"{base_text}；各节点的刚度不同（{per_group}），分档后每档用一个 FEBio 弹簧材料"
                     f"（档数取到每个节点分档后和自己的值差不超过 {100 * tol:g}%）"
                     + ("；每组的总刚度不变" if same_total else "")])
    delta = gen["spring_offset_delta_febio_mm"]
    times = delta / (gen["median_tet_edge_mm"] * k)
    rows.append(["弹簧另一头离组织的距离 δ", f"{delta:.2f} mm（FEBio 坐标，{times:.3g} 倍四面体边长中位数 × k）"])
    nodes = sum(g["spring_nodes"] for g in springy)
    per_node = gen["springs"] / nodes if nodes else None
    rows.append(["弹簧总数", f"{gen['springs']:,} 根"
                 + (f"（每个计算点 {int(per_node)} 根）" if per_node and per_node == int(per_node) else "")])
    blocks["generator"] = table(["项", "数字"], rows)

    s = prov["software"]
    blocks["source"] = table(["项", "值"], [
        ["提交", f"{s['asrp_source']['commit'][:7]}" + ("（有未提交的改动）" if s["asrp_source"]["dirty"] else "")],
        ["软件", f"FEBio {s['febio']}，Python {s['python']}，asrp {s['asrp']}"],
        ["线程", f"{n_threads}"],
        ["开始、结束（UTC）", f"{prov['timing']['started_utc']}、{prov['timing']['finished_utc']}"],
    ])
    return blocks


def sig3(x: float) -> str:
    return f"{x:.3g}"


def load(report_path: Path = REPORT, provenance_path: Path = PROVENANCE) -> dict[str, str]:
    report = json.loads(report_path.read_text(encoding="utf-8"))
    prov = json.loads(provenance_path.read_text(encoding="utf-8"))
    return build(report, prov)


def read_text(path: Path) -> str:
    with open(path, encoding="utf-8", newline=None) as f:  # universal newlines: a CRLF checkout reads as LF
        return f.read()


def find_blocks(text: str) -> tuple[dict[str, tuple[int, int]], list[str]]:
    """Name -> (start, end) of the text between a BEGIN/END pair, and the problems found."""
    spans: dict[str, tuple[int, int]] = {}
    problems: list[str] = []
    open_name = None
    open_at = 0
    for m in MARKER.finditer(text):
        is_begin = m.group(0).startswith("<!-- BEGIN")
        name = m.group(1)
        if is_begin:
            if open_name is not None:
                problems.append(f"{name}: BEGIN inside the unfinished block {open_name}")
            if name in spans:
                problems.append(f"{name}: appears twice")
            open_name, open_at = name, m.end()
        else:
            if open_name != name:
                problems.append(f"{name}: END without its BEGIN")
            else:
                spans[name] = (open_at, m.start())
            open_name = None
    if open_name is not None:
        problems.append(f"{open_name}: BEGIN without its END")
    for m in MARKER.finditer(text):
        line = text[text.rfind("\n", 0, m.start()) + 1:text.find("\n", m.end()) if "\n" in text[m.end():] else len(text)]
        if line.strip() != m.group(0):
            problems.append(f"{m.group(1)}: the marker must be alone on its line")
    return spans, problems


def apply(text: str, blocks: dict[str, str]) -> tuple[str, list[str]]:
    """The page text with every block rewritten, and the problems (missing or unknown markers)."""
    spans, problems = find_blocks(text)
    for name in blocks:
        if name not in spans:
            problems.append(f"{name}: no marker pair in the page")
    for name in spans:
        if name not in blocks:
            problems.append(f"{name}: marker pair has no generator")
    if problems:
        return text, problems
    for name, (start, end) in sorted(spans.items(), key=lambda kv: -kv[1][0]):
        text = text[:start] + "\n" + blocks[name] + "\n" + text[end:]
    return text, []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite the generated blocks in the page")
    mode.add_argument("--check", action="store_true", help="exit 1 if the page differs from what --write would write")
    ap.add_argument("--doc", type=Path, default=DOC, help="the page to check or rewrite (default docs/15-prototype.md)")
    args = ap.parse_args(argv)
    blocks = load()
    if not (args.write or args.check):
        for name, md in blocks.items():
            print(f"--- {name}\n{md}\n")
        return 0
    old = read_text(args.doc)
    new, problems = apply(old, blocks)
    if problems:
        print("prototype page markers are wrong:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    if args.check:
        spans_old, _ = find_blocks(old)
        spans_new, _ = find_blocks(new)
        stale = [n for n in blocks if old[slice(*spans_old[n])] != new[slice(*spans_new[n])]]
        if stale:
            print("docs/15 is out of date with the archived run; run this tool with --write. Differs in block(s): "
                  + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"ok: {len(blocks)} generated blocks match the archived run")
        return 0
    if new != old:
        with open(args.doc, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
    print(f"wrote {len(blocks)} blocks into {args.doc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
